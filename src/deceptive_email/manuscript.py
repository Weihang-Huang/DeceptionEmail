def _header_comment(run_id: str, source_artifact: str) -> str:
    return ("% Generated by deceptive-email manuscript.py\n"
            f"% run_id: {run_id}\n"
            f"% timestamp_utc: {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}\n"
            f"% source_artifact: {source_artifact}\n")


def _fmt(x, ndigits: int = 3) -> str:
    return f"{x:.{ndigits}f}" if isinstance(x, (int, float, np.floating)) else str(x)


def _esc(s) -> str:
    return str(s).replace("%", "\\%").replace("_", "\\_").replace("&", "\\&").replace("#", "\\#")


def generate_dataset_table(clean: pd.DataFrame, run_id: str, out_dir: Path) -> Path:
    cross = pd.crosstab(clean["source"].astype(str), clean["label"])
    cross.columns = ["benign", "positive"]
    cross = cross.reset_index()
    total = pd.DataFrame([{"source": "Total",
                           "benign": int((clean["label"] == 0).sum()),
                           "positive": int((clean["label"] == 1).sum())}])
    cross = pd.concat([cross, total], ignore_index=True)
    cross["total"] = cross["benign"] + cross["positive"]

    lines = [_header_comment(run_id, "outputs/audit/source_class_distribution.csv")]
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Source composition of the cleaned MeAJOR v2.0 dataset "
                 "(after exact-text deduplication).}")
    lines.append("\\label{tab:dataset}")
    lines.append("\\begin{tabular}{lrrr}")
    lines.append("\\hline\\hline")
    lines.append("Source & Benign & Positive & Total \\\\")
    lines.append("\\hline")
    for _, row in cross.iterrows():
        lines.append(f"{_esc(row['source'])} & {row['benign']:,} & {row['positive']:,} & {row['total']:,} \\\\")
    lines.append("\\hline\\hline")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    path = out_dir / "dataset_table.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    provenance.atomic_write_text(path, "\n".join(lines) + "\n")
    return path


