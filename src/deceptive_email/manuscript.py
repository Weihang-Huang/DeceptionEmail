def generate_holdout_table(metrics: pd.DataFrame, run_id: str, out_dir: Path) -> Path:
    """Generate two tables: source-disjoint holdouts and their equal-size controls."""
    sub = metrics[metrics["protocol"] == "source_disjoint"]
    ctrl = metrics[(metrics["protocol"] == "random") & (metrics["split_id"].str.contains("_eq_", regex=False))]
    models_in_metrics = [m for m in MODEL_SHORT if m in sub["model_id"].unique()]
    pivot_h = sub.pivot(index="split_id", columns="model_id", values="macro_f1").reset_index()
    pivot_c = ctrl.pivot(index="split_id", columns="model_id", values="macro_f1").reset_index()
    for m in models_in_metrics:
        pivot_h[m] = pivot_h.get(m, np.nan)
        pivot_c[m] = pivot_c.get(m, np.nan)
    split_info = {}
    for _, row in metrics.drop_duplicates("split_id").iterrows():
        split_info[row["split_id"]] = row

    def _render_table(header: str, caption: str, label: str, pivot: pd.DataFrame,
                      id_to_held) -> list[str]:
        rows = []
        for _, row in pivot.iterrows():
            held = id_to_held(row["split_id"])
            cells = [f"{row.get(m, np.nan):.3f}" for m in models_in_metrics]
            rows.append(f"{_esc(held)} & " + " & ".join(cells) + " \\\\")
        return ([_header_comment(run_id, "outputs/runs/<run_id>/metrics/all_metrics.csv"),
                 "\\begin{table}[t]",
                 "\\centering",
                 f"\\caption{{{caption}}}",
                 f"\\label{{{label}}}",
                 "\\begin{tabular}{l" + "c" * len(models_in_metrics) + "}",
                 "\\hline\\hline",
                 header + " & " + " & ".join(MODEL_SHORT[m] for m in models_in_metrics) + " \\\\",
                 "\\hline"] + rows +
                ["\\hline\\hline", "\\end{tabular}", "\\end{table}"])

    def _held_for_holdout(split_id):
        s = split_info[split_id]
        return "|".join(sorted(s["held_out_sources"].split("|")))

    def _held_for_control(split_id):
        matched = split_id.split("_eq_", 1)[-1]
        s = split_info[matched]
        return "|".join(sorted(s["held_out_sources"].split("|")))

    lines = []
    lines += _render_table(
        "Held-out sources",
        "Macro-F1 on each source-disjoint holdout. Six holdouts (every valid single- and pair-source candidate) are shown.",
        "tab:holdout", pivot_h, _held_for_holdout)
    lines.append("")
    lines += _render_table(
        "Matched holdout",
        "Macro-F1 on the equal-size random control for each source-disjoint holdout. Test size matches the corresponding holdout; train is a stratified random sample of all sources.",
        "tab:eqcontrol", pivot_c, _held_for_control)

    path = out_dir / "holdout_table.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    provenance.atomic_write_text(path, "\n".join(lines) + "\n")
    return path


