    lines.append(r"\newcommand{\NDocs}{" + f"{n_docs:,}" + "}")
    lines.append(r"\newcommand{\NPos}{" + f"{n_pos:,}" + "}")
    lines.append(r"\newcommand{\NNeg}{" + f"{n_neg:,}" + "}")
    lines.append(r"\newcommand{\NSources}{" + f"{n_sources}" + "}")
