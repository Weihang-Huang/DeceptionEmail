def generate_figures(metrics: pd.DataFrame, clean: pd.DataFrame,
                     eff: pd.DataFrame, run_id: str, out_dir: Path) -> list[Path]:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    files = []
    colors = {"word_logistic_regression": "#1f77b4",
              "character_linear_svm": "#ff7f0e",
              "structural_logistic_regression": "#2ca02c",
              "word_xgboost": "#d62728",
              "word_noanon_logistic_regression": "#9467bd",
              "character_noanon_linear_svm": "#8c564b"}

    # Figure 1: source by class counts.
    cross = pd.crosstab(clean["source"].astype(str), clean["label"]).sort_index()
    fig, ax = plt.subplots(figsize=(3.6, 2.4))
    ax.bar(cross.index, cross[0], color="#c9d6e3", label="benign")
    ax.bar(cross.index, cross[1], bottom=cross[0], color="#7a9c5b", label="positive")
    ax.set_ylabel("Emails")
    ax.tick_params(axis="x", rotation=25, labelsize=7)
    ax.legend(fontsize=7, frameon=False)
    fig.tight_layout()
    p = out_dir / "source_class_distribution.pdf"
    fig.savefig(p)
    fig.savefig(out_dir / "source_class_distribution.png", dpi=300)
    plt.close(fig)
    files.append(p)

    # Figure 2: random vs source-disjoint macro-F1 per model.
    models = [m for m in MODEL_SHORT if m in set(metrics["model_id"])]
    random_vals = [metrics[(metrics["model_id"] == m) & (metrics["protocol"] == "random")
                           & (metrics["split_id"] == "random_seed42")]["macro_f1"].max()
                   for m in models]
    holdout_vals = [metrics[(metrics["model_id"] == m) & (metrics["protocol"] == "source_disjoint")]["macro_f1"].values
                    for m in models]
    x = np.arange(len(models))
    w = 0.4
    fig, ax = plt.subplots(figsize=(3.6, 2.4))
    ax.bar(x - w / 2, random_vals, w, color=[colors[m] for m in models], label="random")
    for i, hv in enumerate(holdout_vals):
        for j, v in enumerate(hv):
            ax.plot([i + w / 2], [v], marker="o", markersize=3, color=colors[models[i]])
    ax.set_xticks(x)
    ax.set_xticklabels([MODEL_SHORT[m] for m in models])
    ax.set_ylabel("Macro-F1")
    ax.set_ylim(0, 1)
    ax.legend(loc="lower right", fontsize=7, frameon=False)
    fig.tight_layout()
    p = out_dir / "random_vs_source_disjoint.pdf"
    fig.savefig(p)
    fig.savefig(out_dir / "random_vs_source_disjoint.png", dpi=300)
    plt.close(fig)
    files.append(p)

    # Figure 3: generalisation gap per model per holdout.
    fig, ax = plt.subplots(figsize=(3.6, 2.4))
    pos = 0
    labels = []
    for m in models:
        rv = metrics[(metrics["model_id"] == m) & (metrics["protocol"] == "random")
                     & (metrics["split_id"] == "random_seed42")]["macro_f1"].max()
        for _, row in metrics[(metrics["model_id"] == m) & (metrics["protocol"] == "source_disjoint")].iterrows():
            gap = rv - row["macro_f1"]
            ax.bar([pos], [gap], color=colors[m], width=0.6)
            labels.append(f"{MODEL_SHORT[m]}/{row['split_id'].replace('holdout_','h')}")
            pos += 1
    ax.axhline(0, color="black", linewidth=0.8)
    ax.set_xticks(range(pos))
    ax.set_xticklabels(labels, fontsize=6, rotation=30, ha="right")
    ax.set_ylabel("Random F1 minus source-disjoint F1")
    fig.tight_layout()
    p = out_dir / "generalisation_gap.pdf"
    fig.savefig(p)
    fig.savefig(out_dir / "generalisation_gap.png", dpi=300)
    plt.close(fig)
    files.append(p)

    # Figure 4: accuracy-efficiency tradeoff (source-disjoint mean macro-F1 vs inference time).
    fig, ax = plt.subplots(figsize=(3.6, 2.4))
    for m in models:
        f1v = metrics[(metrics["model_id"] == m) & (metrics["protocol"] == "source_disjoint")]["macro_f1"].mean()
        eff_row = eff[eff["model_id"] == m].iloc[0]
        ax.scatter([eff_row["inference_time_s_per_1000"] * 1000], [f1v],
                   color=colors[m], s=60, zorder=3)
        ax.annotate(MODEL_SHORT[m], (eff_row["inference_time_s_per_1000"] * 1000, f1v),
                    textcoords="offset points", xytext=(6, 4), fontsize=8)
    ax.set_xlabel("Inference time (ms per 1,000 messages)")
    ax.set_ylabel("Mean source-disjoint macro-F1")
    ax.grid(True, which="both", alpha=0.3)
    fig.tight_layout()
    p = out_dir / "accuracy_efficiency_tradeoff.pdf"
    fig.savefig(p)
    fig.savefig(out_dir / "accuracy_efficiency_tradeoff.png", dpi=300)
    plt.close(fig)
    files.append(p)

    # Figure 5: protocol comparison (mean macro-F1 by protocol x model, error bars = 95% CI).
    fig, ax = plt.subplots(figsize=(3.6, 2.4))
    protocols = ["random", "random_cluster_disjoint_pooled", "source_disjoint",
                 "cluster_disjoint", "joint_source_cluster_disjoint"]
    proto_labels = ["random", "pooled cluster-disjoint", "source-disjoint",
                    "cluster-disjoint", "joint"]
    x = np.arange(len(models))
    width = 0.15
    colors5 = ["#4c72b0", "#55a868", "#dd8452", "#c44e52", "#8172b2"]
    for pi, proto in enumerate(protocols):
        means = []
        errs = []
        for m in models:
            sub = metrics[(metrics["model_id"] == m) & (metrics["protocol"] == proto)]
            if len(sub) == 0:
                means.append(np.nan)
                errs.append(0.0)
                continue
            means.append(sub["macro_f1"].mean())
            errs.append(sub["macro_f1"].std() / np.sqrt(len(sub)))
        ax.bar(x + (pi - 2) * width, means, width, label=proto_labels[pi],
               yerr=errs, capsize=2, color=colors5[pi])
    ax.set_xticks(x)
    ax.set_xticklabels([MODEL_SHORT[m] for m in models])
    ax.set_ylabel("Mean macro-F1 (across holdouts)")
    ax.set_ylim(0, 1)
    ax.legend(fontsize=5.5, frameon=False, loc="lower right")
    fig.tight_layout()
    p = out_dir / "protocol_comparison.pdf"
    fig.savefig(p)
    fig.savefig(out_dir / "protocol_comparison.png", dpi=300)
    plt.close(fig)
    files.append(p)

    return files


def generate_auc_table(run_id: str, out_dir: Path) -> Path:
    """PR-AUC, ROC-AUC, and Brier for the six source-disjoint holdouts."""
    extra_path = Path("outputs/runs") / run_id / "metrics/extra_metrics.csv"
    if not extra_path.exists():
        return None
    extra = pd.read_csv(extra_path)
    sub = extra[extra["protocol"] == "source_disjoint"].copy()
    sub["held"] = sub["split_id"].str.replace("holdout_", "").str.replace("_", "|")
    sub = sub.sort_values(["held", "model_id"])
    lines = [_header_comment(run_id, "outputs/runs/<run_id>/metrics/extra_metrics.csv")]
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Rank-based and calibration metrics on the six source-disjoint "
                 "holdouts. PR-AUC and ROC-AUC use the positive-class probability for "
                 "probabilistic models and the decision score for the linear SVMs (M2, A2); "
                 "Brier is unavailable for the linear SVMs, which do not produce calibrated "
                 "probabilities.}")
    lines.append("\\label{tab:auc}")
    lines.append("\\begin{tabular}{llccc}")
    lines.append("\\hline\\hline")
    lines.append("Held-out & Model & PR-AUC & ROC-AUC & Brier \\\\")
    lines.append("\\hline")
    for _, row in sub.iterrows():
        m = MODEL_SHORT.get(row["model_id"], row["model_id"])
        pr = f"{row['pr_auc']:.3f}" if pd.notna(row.get("pr_auc")) else "--"
        roc = f"{row['roc_auc']:.3f}" if pd.notna(row.get("roc_auc")) else "--"
        br = f"{row['brier']:.3f}" if pd.notna(row.get("brier")) else "--"
        lines.append(f"{_esc(str(row['held']))} & {m} & {pr} & {roc} & {br} \\\\")
    lines.append("\\hline\\hline")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    path = out_dir / "auc_table.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    provenance.atomic_write_text(path, "\n".join(lines) + "\n")
    return path


def generate_paper_artifacts(run_id: str, clean: pd.DataFrame, metrics: pd.DataFrame,
                             eff: pd.DataFrame, run_dir: Path, paper_generated: Path,
                             paper_figures: Path) -> dict:
    run_dir = Path(run_dir)
    paper_generated = Path(paper_generated)
    paper_figures = Path(paper_figures)
    paper_generated.mkdir(parents=True, exist_ok=True)
    paper_figures.mkdir(parents=True, exist_ok=True)

    paths = {
        "dataset_table": generate_dataset_table(clean, run_id, paper_generated),
        "performance_table": generate_performance_table(metrics, run_id, paper_generated),
        "efficiency_table": generate_efficiency_table(eff, run_id, paper_generated),
        "holdout_table": generate_holdout_table(metrics, run_id, paper_generated),
        "per_model_gap": generate_per_model_gap_table(metrics, run_id, paper_generated),
        "cluster_leakage": generate_cluster_leakage_table(run_id, paper_generated),
        "decomposition": generate_decomposition_table(run_id, paper_generated),
        "paired_delta": generate_paired_delta_table(metrics, run_id, paper_generated),
        "auc_table": generate_auc_table(run_id, paper_generated),
        "result_macros": generate_result_macros(metrics, clean, run_id, paper_generated),
    }
    fig_dir = run_dir / "figures"
    figures = generate_figures(metrics, clean, eff, run_id, fig_dir)
    copies = []
    import shutil
    for f in figures:
        for ext in (".pdf", ".png"):
            src = f.with_suffix(ext)
            if src.exists():
                dst = paper_figures / src.name
                shutil.copy2(src, dst)
                copies.append(str(dst))
    paths["figures"] = copies
    return paths
