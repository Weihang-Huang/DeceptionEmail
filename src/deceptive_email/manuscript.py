def generate_cluster_leakage_table(run_id: str, out_dir: Path) -> Path:
    """Cross-split SimHash pair counts per protocol per holdout."""
    leak_path = Path("outputs/splits/cluster_leakage.csv")
    if not leak_path.exists():
        return None
    leak = pd.read_csv(leak_path)
    # Keep only source-disjoint, cluster-disjoint, joint, pooled, and fullmatch rows.
    keep = leak[leak["protocol"].isin(
        ["source_disjoint", "cluster_disjoint", "joint_source_cluster_disjoint",
         "random_cluster_disjoint_pooled", "random_fullmatch"])].copy()
    keep["held"] = keep["split_id"].str.split("holdout_", n=1).str[-1].str.replace("_", "|")
    pivot = keep.pivot(index="held", columns="protocol", values="n_pairs").reset_index()
    pivot_rows = keep.pivot(index="held", columns="protocol", values="n_rows_involved").reset_index()
    lines = [_header_comment(run_id, "outputs/splits/cluster_leakage.csv")]
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Cross-split exact-SimHash pairs (rows sharing a 64-bit SimHash "
                 "component that straddle the train/test boundary) by protocol. Source-disjoint "
                 "splits still leak cross-source template replication; the cluster-disjoint, "
                 "joint, and pooled cluster-disjoint protocols eliminate them by construction. "
                 "Pair counts are dominated by a few large template families, so the distinct-row "
                 "counts (in parentheses) bound the practical footprint.}")
    lines.append("\\label{tab:cluster_leakage}")
    lines.append("\\begin{tabular}{lccccc}")
    lines.append("\\hline\\hline")
    lines.append("Held-out & Source-disjoint & Cluster-disjoint & Joint & Pooled cluster-disjoint & Random full-match \\\\")
    lines.append("\\hline")
    for _, row in pivot.iterrows():
        held = str(row["held"])
        def _cell(proto):
            v = row.get(proto, 0)
            r = pivot_rows.loc[pivot_rows["held"] == held, proto].iloc[0] if held in set(pivot_rows["held"]) else 0
            if pd.isna(v):
                return "--"
            return f"{int(v):,} ({int(r):,})"
        lines.append(f"{_esc(held)} & {_cell('source_disjoint')} & "
                     f"{_cell('cluster_disjoint')} & {_cell('joint_source_cluster_disjoint')} & "
                     f"{_cell('random_cluster_disjoint_pooled')} & {_cell('random_fullmatch')} \\\\")
    lines.append("\\hline\\hline")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    path = out_dir / "cluster_leakage.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    provenance.atomic_write_text(path, "\n".join(lines) + "\n")
    return path


def generate_decomposition_table(run_id: str, out_dir: Path) -> Path:
    """Source predictability, PSI/KS, OOV share, and recalibration gain."""
    div_path = Path("outputs/runs") / run_id / "metrics/distribution_divergence.csv"
    cal_path = Path("outputs/runs") / run_id / "metrics/calibration_recalibration.csv"
    if not div_path.exists() or not cal_path.exists():
        return None
    div = pd.read_csv(div_path)
    cal = pd.read_csv(cal_path)
    # Recalibration gain per holdout: mean delta across probabilistic models.
    cal_mean = cal.groupby("split_id")["delta_macro_f1"].mean().reset_index()
    cal_mean.columns = ["split_id", "recal_gain"]
    merged = div.merge(cal_mean, on="split_id", how="left")
    lines = [_header_comment(run_id, "outputs/runs/<run_id>/metrics/distribution_divergence.csv")]
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Decomposition of the source-disjoint drop. Source predictability is "
                 "the 3-fold CV accuracy of a source classifier on the training partition (chance "
                 "0.5 for two-source training). PSI and KS quantify train/test TF-IDF divergence; "
                 "OOV is the test-token share absent from the training vocabulary; recalibration "
                 "gain is the mean macro-F1 change from training-only isotonic threshold "
                 "recalibration across probabilistic models.}")
    lines.append("\\label{tab:decomposition}")
    lines.append("\\begin{tabular}{lcccccc}")
    lines.append("\\hline\\hline")
    lines.append("Holdout & Source pred. & PSI & KS & OOV share & Recal. gain \\\\")
    lines.append("\\hline")
    for _, row in merged.iterrows():
        held = str(row["split_id"]).replace("holdout_", "").replace("_", "|")
        sp = f"{row['cv_accuracy']:.3f}" if pd.notna(row.get("cv_accuracy")) else "--"
        psi = f"{row['psi']:.3f}" if pd.notna(row.get("psi")) else "--"
        ks = f"{row['ks_statistic']:.3f}" if pd.notna(row.get("ks_statistic")) else "--"
        oov = f"{row['oov_share']:.3f}" if pd.notna(row.get("oov_share")) else "--"
        rg = f"{row['recal_gain']:+.3f}" if pd.notna(row.get("recal_gain")) else "--"
        lines.append(f"{_esc(held)} & {sp} & {psi} & {ks} & {oov} & {rg} \\\\")
    lines.append("\\hline\\hline")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    path = out_dir / "decomposition.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    provenance.atomic_write_text(path, "\n".join(lines) + "\n")
    return path


